// Целевая кривая веса: -1.5 кг за месяц от старта
export function targetWeight(date: Date): number {
  const start = new Date(PLAN_META.start);
  const months = (date.getFullYear() - start.getFullYear()) * 12 + (date.getMonth() - start.getMonth()) + (date.getDate() - start.getDate()) / 30;
  const w = 110 - 1.5 * months;
  return Math.max(92, Math.min(110, w));
}

